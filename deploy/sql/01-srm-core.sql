-- MySQL 8 local development bootstrap. Never run upstream bootstrap against an existing production database.
CREATE TABLE IF NOT EXISTS SRM_SUPPLIER (
 ID varchar(20) PRIMARY KEY, SUPPLIER_CODE varchar(32) NOT NULL UNIQUE,
 NAME varchar(128) NOT NULL, CATEGORY varchar(32) NOT NULL, TIER varchar(16) NOT NULL,
 STATUS varchar(16) NOT NULL DEFAULT 'POTENTIAL', ORG_ID varchar(20) NOT NULL,
 ADDRESS varchar(255), CREDIT_CODE varchar(512), BANK_ACCOUNT varchar(512),
 DELETE_FLAG varchar(16) NOT NULL DEFAULT 'NOT_DELETE', CREATE_TIME datetime, CREATE_USER varchar(20),
 UPDATE_TIME datetime, UPDATE_USER varchar(20), INDEX idx_srm_supplier_org (ORG_ID, STATUS)
);

CREATE TABLE IF NOT EXISTS SRM_SUPPLIER_CERT (
 ID varchar(20) PRIMARY KEY, SUPPLIER_ID varchar(20) NOT NULL,
 CERT_TYPE varchar(32) NOT NULL, CERT_NO varchar(64) NOT NULL,
 VALID_FROM date NOT NULL, VALID_TO date NOT NULL, FILE_ID varchar(64) NOT NULL,
 VERSION int NOT NULL DEFAULT 1, STATUS varchar(16) NOT NULL,
 DELETE_FLAG varchar(16) NOT NULL DEFAULT 'NOT_DELETE', CREATE_TIME datetime, CREATE_USER varchar(20),
 UPDATE_TIME datetime, UPDATE_USER varchar(20),
 CONSTRAINT fk_cert_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID),
 CONSTRAINT ck_cert_dates CHECK (VALID_TO >= VALID_FROM), INDEX idx_cert_expiry (VALID_TO)
);
CREATE TABLE IF NOT EXISTS SRM_SUPPLIER_CONTACT (
 ID varchar(20) PRIMARY KEY, SUPPLIER_ID varchar(20) NOT NULL,
 NAME varchar(32) NOT NULL, PHONE varchar(512) NOT NULL, EMAIL varchar(64),
 ROLES json NOT NULL, ENABLED boolean NOT NULL DEFAULT true, ACCOUNT_ID varchar(20) UNIQUE,
 DELETE_FLAG varchar(16) NOT NULL DEFAULT 'NOT_DELETE', CREATE_TIME datetime, CREATE_USER varchar(20),
 UPDATE_TIME datetime, UPDATE_USER varchar(20),
 CONSTRAINT fk_contact_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
