CREATE TABLE IF NOT EXISTS SRM_SRC_RFQ (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, RFQ_NO varchar(64) NOT NULL UNIQUE,
 TITLE varchar(128) NOT NULL, CATEGORY varchar(32) NOT NULL, STRATEGY varchar(16) NOT NULL,
 CURRENCY char(3) NOT NULL, STATUS varchar(20) NOT NULL, DEADLINE_MS bigint NOT NULL,
 START_MS bigint NOT NULL, CONFIG_CIPHER mediumtext NOT NULL, LOWEST_CIPHER text NULL,
 WINNING_BID_ID varchar(20) NULL, ROW_VERSION bigint NOT NULL DEFAULT 0,
 LAST_TIME_MS bigint NOT NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL,
 UNIQUE KEY uq_src_request(ORG_ID,REQUEST_KEY), INDEX idx_src_scope(ORG_ID,CREATED_BY,STATUS), INDEX idx_src_due(STATUS,DEADLINE_MS)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_INVITE (
 RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL, ALIAS varchar(32) NOT NULL,
 PRIMARY KEY(RFQ_ID,SUPPLIER_ID), UNIQUE KEY uq_src_alias(RFQ_ID,ALIAS),
 FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID), FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_QUOTE (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 ROUND_NO bigint NOT NULL, PAYLOAD_CIPHER mediumtext NOT NULL, TOTAL_CIPHER text NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL, CREATED_BY varchar(20) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_src_quote_round(RFQ_ID,SUPPLIER_ID,ROUND_NO),
 UNIQUE KEY uq_src_quote_key(RFQ_ID,SUPPLIER_ID,REQUEST_KEY), FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_BID (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 AMOUNT_CIPHER text NOT NULL, SEQUENCE_NO bigint NOT NULL, REQUEST_KEY varchar(64) NOT NULL,
 REQUEST_HASH char(64) NOT NULL, ACCEPTED_MS bigint NOT NULL, END_MS bigint NOT NULL,
 CREATED_BY varchar(20) NOT NULL, UNIQUE KEY uq_src_bid_sequence(RFQ_ID,SEQUENCE_NO),
 UNIQUE KEY uq_src_bid_request(RFQ_ID,SUPPLIER_ID,REQUEST_KEY), FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_QUESTION (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NULL,
 IS_PUBLIC boolean NOT NULL, QUESTION varchar(2000) NOT NULL, ANSWER varchar(2000) NULL,
 CREATED_BY varchar(20) NOT NULL, ANSWERED_BY varchar(20) NULL, CREATED_AT datetime(3) NOT NULL,
 ANSWERED_AT datetime(3) NULL, FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_FILE (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, ORG_ID varchar(20) NOT NULL,
 FILE_NAME varchar(128) NOT NULL, MIME varchar(64) NOT NULL, CONTENT_SHA256 char(64) NOT NULL,
 STORAGE_ENGINE varchar(16) NOT NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_RISK (
 ID varchar(20) PRIMARY KEY, SUPPLIER_ID varchar(20) NOT NULL, ORG_ID varchar(20) NOT NULL,
 LEVEL varchar(16) NOT NULL, EVIDENCE_REF varchar(256) NOT NULL, NOTE varchar(1000) NOT NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 INDEX idx_src_risk(SUPPLIER_ID,CREATED_AT), FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_AWARD (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 PROCESS_ID varchar(64) NOT NULL UNIQUE, STATUS varchar(20) NOT NULL,
 SNAPSHOT_CIPHER mediumtext NOT NULL, BASIS_HASH char(64) NOT NULL, REASON varchar(1000) NOT NULL,
 NO_HISTORY_REASON varchar(1000) NULL, DISCLOSE_LOSS boolean NOT NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 REVIEWED_BY varchar(20) NULL, REVIEW_COMMENT varchar(1000) NULL, PUBLISHED_AT datetime(3) NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL,
 UNIQUE KEY uq_src_award_request(RFQ_ID,REQUEST_KEY), INDEX idx_src_award(RFQ_ID,STATUS),
 FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID), FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_AWARD_ACTION (
 ID varchar(20) PRIMARY KEY, AWARD_ID varchar(20) NOT NULL, TASK_ID varchar(64) NOT NULL,
 ACTION varchar(24) NOT NULL, ACTOR_ID varchar(20) NOT NULL, TARGET_ID varchar(20) NULL,
 COMMENT varchar(1000) NOT NULL, CREATED_AT datetime(3) NOT NULL, FOREIGN KEY(AWARD_ID) REFERENCES SRM_SRC_AWARD(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_NOTICE (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 KIND varchar(24) NOT NULL, MESSAGE varchar(1000) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 INDEX idx_src_notice(SUPPLIER_ID,CREATED_AT), FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SRC_EVENT (
 ID varchar(20) PRIMARY KEY, RFQ_ID varchar(20) NOT NULL, VERSION bigint NOT NULL,
 STATUS varchar(16) NOT NULL DEFAULT 'PENDING', ATTEMPTS int NOT NULL DEFAULT 0,
 CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_src_event(RFQ_ID,VERSION),
 INDEX idx_src_event_pending(STATUS,CREATED_AT), FOREIGN KEY(RFQ_ID) REFERENCES SRM_SRC_RFQ(ID)
);
