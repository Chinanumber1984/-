-- P7 additive ledgers. No changes to existing user, credential or historical business rows.
CREATE TABLE IF NOT EXISTS SRM_QL_CASE (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,
 KIND varchar(8) NOT NULL,TITLE varchar(128) NOT NULL,STATUS varchar(20) NOT NULL,
 ROW_VERSION bigint NOT NULL DEFAULT 0,REVISION bigint NOT NULL DEFAULT 0,
 PROCESS_ID varchar(64) NULL,SUBMITTED_BY varchar(20) NULL,REVIEWED_BY varchar(20) NULL,
 REVIEW_CIPHER text NULL,META_CIPHER mediumtext NOT NULL,PAYLOAD_CIPHER mediumtext NULL,
 DEFECT_KEY varchar(80) NULL,SEVERITY varchar(12) NULL,DUE_MS bigint NULL,
 CREATED_BY varchar(20) NOT NULL,REQUEST_KEY varchar(64) NOT NULL,REQUEST_HASH char(64) NOT NULL,
 CREATED_AT datetime(3) NOT NULL,UPDATED_AT datetime(3) NOT NULL,CLOSED_AT datetime(3) NULL,
 UNIQUE KEY uq_ql_request(ORG_ID,KIND,REQUEST_KEY), INDEX idx_ql_scope(ORG_ID,SUPPLIER_ID,STATUS),
 INDEX idx_ql_defect(SUPPLIER_ID,DEFECT_KEY,CREATED_AT),FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_QL_REVISION (
 ID varchar(20) PRIMARY KEY,CASE_ID varchar(20) NOT NULL,REVISION bigint NOT NULL,
 PROCESS_ID varchar(64) NOT NULL,PAYLOAD_CIPHER mediumtext NOT NULL,STATUS varchar(20) NOT NULL,
 SUBMITTED_BY varchar(20) NOT NULL,REVIEWED_BY varchar(20) NULL,REVIEW_CIPHER text NULL,
 CREATED_AT datetime(3) NOT NULL,CLOSED_AT datetime(3) NULL,UNIQUE KEY uq_ql_revision(CASE_ID,REVISION)
);
CREATE TABLE IF NOT EXISTS SRM_QL_ACTION (
 ID varchar(20) PRIMARY KEY,CASE_ID varchar(20) NOT NULL,ACTION varchar(32) NOT NULL,
 ACTOR_ID varchar(20) NOT NULL,CONTENT_CIPHER mediumtext NOT NULL,CREATED_AT datetime(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS SRM_QL_FILE (
 ID varchar(20) PRIMARY KEY,CASE_ID varchar(20) NOT NULL,ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,
 FILE_NAME varchar(128) NOT NULL,MIME varchar(64) NOT NULL,CONTENT_SHA256 char(64) NOT NULL,
 BYTE_SIZE bigint NOT NULL,STORAGE_ENGINE varchar(16) NOT NULL,CREATED_BY varchar(20) NOT NULL,CREATED_AT datetime(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS SRM_QL_POLICY (
 ID varchar(20) PRIMARY KEY,ORG_ID varchar(20) NOT NULL,VERSION bigint NOT NULL,
 CONFIG mediumtext NOT NULL,REASON varchar(500) NOT NULL,CREATED_BY varchar(20) NOT NULL,CREATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_ql_policy(ORG_ID,VERSION)
);
CREATE TABLE IF NOT EXISTS SRM_QL_RISK (
 ID varchar(20) PRIMARY KEY,ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,
 RISK_TYPE varchar(32) NOT NULL,EVENT_KEY varchar(128) NOT NULL,SOURCE varchar(16) NOT NULL DEFAULT 'INTERNAL',
 ORIGIN_KIND varchar(20) NOT NULL,BASIS_CIPHER mediumtext NOT NULL,STATUS varchar(20) NOT NULL,
 LEVEL varchar(8) NULL,ROW_VERSION bigint NOT NULL DEFAULT 0,ASSESSMENT_CIPHER text NULL,ASSESSED_BY varchar(20) NULL,
 FREEZE_SUGGESTED boolean NOT NULL DEFAULT false,FREEZE_APPROVAL_ID varchar(20) NULL,
 CREATED_BY varchar(20) NOT NULL,CREATED_AT datetime(3) NOT NULL,UPDATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_ql_risk(EVENT_KEY),INDEX idx_ql_risk_scope(ORG_ID,SUPPLIER_ID,STATUS)
);
CREATE TABLE IF NOT EXISTS SRM_QL_RISK_ACTION (
 ID varchar(20) PRIMARY KEY,RISK_ID varchar(20) NOT NULL,ACTION varchar(32) NOT NULL,
 ACTOR_ID varchar(20) NOT NULL,CONTENT_CIPHER mediumtext NOT NULL,CREATED_AT datetime(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS SRM_QL_NOTICE (
 ID varchar(20) PRIMARY KEY,ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,
 CREATED_BY varchar(20) NOT NULL,AUDIENCE varchar(12) NOT NULL,BUSINESS_ID varchar(20) NOT NULL,MESSAGE varchar(500) NOT NULL,
 EVENT_KEY varchar(128) NOT NULL,CREATED_AT datetime(3) NOT NULL,UNIQUE KEY uq_ql_notice(AUDIENCE,EVENT_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_QL_SOURCE_MAP (
 CONNECTOR_ID varchar(20) NOT NULL,EXTERNAL_KEY varchar(80) NOT NULL,ORG_ID varchar(20) NOT NULL,
 SUPPLIER_ID varchar(20) NOT NULL,CREATED_BY varchar(20) NOT NULL,CREATED_AT datetime(3) NOT NULL,
 PRIMARY KEY(CONNECTOR_ID,EXTERNAL_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_QL_INSPECTION (
 ID varchar(20) PRIMARY KEY,ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,
 CONNECTOR_ID varchar(20) NOT NULL,EXTERNAL_KEY varchar(96) NOT NULL,SOURCE_VERSION bigint NOT NULL,
 MODE varchar(12) NOT NULL,PERIOD char(7) NOT NULL,RESULT varchar(8) NOT NULL,SEVERITY varchar(12) NOT NULL,
 DEDUCTION decimal(5,2) NOT NULL,POLICY_VERSION bigint NOT NULL,PAYLOAD_CIPHER mediumtext NOT NULL,
 CREATED_BY varchar(20) NOT NULL,CREATED_AT datetime(3) NOT NULL,UPDATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_ql_inspection(CONNECTOR_ID,EXTERNAL_KEY),INDEX idx_ql_period(SUPPLIER_ID,PERIOD,MODE)
);
CREATE TABLE IF NOT EXISTS SRM_QL_ERP_SCORE (
 CONNECTOR_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,ORG_ID varchar(20) NOT NULL,
 PERIOD char(7) NOT NULL,MODE varchar(12) NOT NULL,SOURCE_VERSION bigint NOT NULL,
 PAYLOAD_CIPHER mediumtext NOT NULL,UPDATED_AT datetime(3) NOT NULL,
 PRIMARY KEY(CONNECTOR_ID,SUPPLIER_ID,PERIOD)
);
CREATE TABLE IF NOT EXISTS SRM_QL_SCORE_PUBLICATION (
 ID varchar(20) PRIMARY KEY,ORG_ID varchar(20) NOT NULL,SUPPLIER_ID varchar(20) NOT NULL,PERIOD char(7) NOT NULL,
 BASIS_HASH char(64) NOT NULL,INPUT_ID varchar(20) NOT NULL,MODE varchar(12) NOT NULL,
 CREATED_AT datetime(3) NOT NULL,UNIQUE KEY uq_ql_score_basis(SUPPLIER_ID,PERIOD,BASIS_HASH)
);
