CREATE TABLE IF NOT EXISTS SRM_PERF_IMPORT (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, REQUEST_KEY varchar(64) NOT NULL,
 CONTENT_HASH char(64) NOT NULL, ROW_COUNT int NOT NULL, CREATED_BY varchar(20) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_perf_import(ORG_ID,REQUEST_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_PERF_INPUT (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 PERIOD char(7) NOT NULL, REVISION bigint NOT NULL, SOURCE_TYPE varchar(20) NOT NULL,
 SOURCE_REF varchar(256) NOT NULL, SCORES json NOT NULL, IMPORT_ID varchar(20) NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_perf_input(SUPPLIER_ID,PERIOD,REVISION),
 INDEX idx_perf_input_period(PERIOD,ORG_ID),
 FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_SCORECARD (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 PERIOD char(7) NOT NULL, INPUT_ID varchar(20) NOT NULL, TEMPLATE_ID bigint NOT NULL,
 DELIVER_SCORE decimal(5,2) NOT NULL, QUALITY_SCORE decimal(5,2) NOT NULL,
 COST_SCORE decimal(5,2) NOT NULL, SERVICE_SCORE decimal(5,2) NOT NULL,
 TOTAL decimal(5,2) NOT NULL, GRADE varchar(24) NOT NULL, ROW_VERSION bigint NOT NULL,
 UPDATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_scorecard_period(SUPPLIER_ID,PERIOD), INDEX idx_scorecard_scope(ORG_ID,PERIOD,GRADE),
 FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID),
 FOREIGN KEY(INPUT_ID) REFERENCES SRM_PERF_INPUT(ID), FOREIGN KEY(TEMPLATE_ID) REFERENCES SRM_PERF_TEMPLATE(ID)
);
CREATE TABLE IF NOT EXISTS SRM_PERF_SCORE_VERSION (
 ID varchar(20) PRIMARY KEY, SCORE_ID varchar(20) NOT NULL, REVISION bigint NOT NULL,
 SNAPSHOT json NOT NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_perf_score_version(SCORE_ID,REVISION), FOREIGN KEY(SCORE_ID) REFERENCES SRM_SCORECARD(ID)
);
CREATE TABLE IF NOT EXISTS SRM_PERF_APPEAL (
 ID varchar(20) PRIMARY KEY, SCORE_ID varchar(20) NOT NULL, SCORE_VERSION bigint NOT NULL,
 STATUS varchar(16) NOT NULL, REASON varchar(1000) NOT NULL, CREATED_BY varchar(20) NOT NULL,
 REVIEW_COMMENT varchar(1000) NULL, REVIEWED_BY varchar(20) NULL, CREATED_AT datetime(3) NOT NULL,
 REVIEWED_AT datetime(3) NULL, INDEX idx_perf_appeal(SCORE_ID,STATUS),
 FOREIGN KEY(SCORE_ID) REFERENCES SRM_SCORECARD(ID)
);
