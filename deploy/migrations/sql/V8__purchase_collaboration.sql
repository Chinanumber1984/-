CREATE TABLE IF NOT EXISTS SRM_COL_CASE_ACTION (
 ID varchar(20) PRIMARY KEY, CASE_ID varchar(20) NOT NULL, ACTION varchar(24) NOT NULL,
 ACTOR_ID varchar(20) NOT NULL, COMMENT_CIPHER text NOT NULL, CREATED_AT datetime(3) NOT NULL
);
CREATE TABLE IF NOT EXISTS SRM_COL_FILE (
 ID varchar(20) PRIMARY KEY, RECON_ID varchar(20) NOT NULL, ORG_ID varchar(20) NOT NULL,
 SUPPLIER_ID varchar(20) NOT NULL, FILE_NAME varchar(128) NOT NULL, MIME varchar(64) NOT NULL,
