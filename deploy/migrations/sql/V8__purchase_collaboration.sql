);
CREATE TABLE IF NOT EXISTS SRM_COL_INVOICE (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 RECON_ID varchar(20) NOT NULL, INVOICE_NO varchar(64) NOT NULL, CURRENCY char(3) NOT NULL,
 AMOUNT_CIPHER text NOT NULL, FILE_ID varchar(20) NOT NULL, REVISION bigint NOT NULL DEFAULT 1,
 ROW_VERSION bigint NOT NULL DEFAULT 0, STATUS varchar(24) NOT NULL, OUTBOX_ID varchar(20) NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL,
 UNIQUE KEY uq_col_invoice_no(ORG_ID,SUPPLIER_ID,INVOICE_NO), UNIQUE KEY uq_col_invoice_req(RECON_ID,REQUEST_KEY),
 FOREIGN KEY(RECON_ID) REFERENCES SRM_COL_RECON(ID), FOREIGN KEY(FILE_ID) REFERENCES SRM_COL_FILE(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_INVOICE_REV (
 ID varchar(20) PRIMARY KEY, INVOICE_ID varchar(20) NOT NULL, REVISION bigint NOT NULL,
 FILE_ID varchar(20) NOT NULL, AMOUNT_CIPHER text NOT NULL, REASON_CIPHER text NOT NULL,
