 UPDATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_col_risk(EVENT_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_COL_NOTICE (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 CREATED_BY varchar(20) NOT NULL, AUDIENCE varchar(16) NOT NULL, BUSINESS_ID varchar(20) NOT NULL,
 KIND varchar(32) NOT NULL, MESSAGE varchar(500) NOT NULL, EVENT_KEY varchar(160) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_col_notice(AUDIENCE,EVENT_KEY), INDEX idx_col_notice(ORG_ID,SUPPLIER_ID)
