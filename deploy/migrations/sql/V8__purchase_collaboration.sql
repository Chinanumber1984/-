-- Additive P6 business ledger and durable, versioned integration. Existing data/keys untouched.
CREATE TABLE IF NOT EXISTS SRM_XCH_CONNECTOR (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SYSTEM_KEY varchar(16) NOT NULL,
 NAME varchar(80) NOT NULL, MODE varchar(12) NOT NULL, ENDPOINT varchar(512) NOT NULL,
 SECRET_CIPHER text NOT NULL, SECRET_FP char(64) NOT NULL, ENABLED boolean NOT NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_xch_name(ORG_ID,NAME), INDEX idx_xch_target(ORG_ID,SYSTEM_KEY,MODE,ENABLED)
);
CREATE TABLE IF NOT EXISTS SRM_XCH_NONCE (
 CONNECTOR_ID varchar(20) NOT NULL, NONCE varchar(64) NOT NULL, EXPIRES_MS bigint NOT NULL,
 PRIMARY KEY(CONNECTOR_ID,NONCE), INDEX idx_xch_nonce_exp(EXPIRES_MS)
);
CREATE TABLE IF NOT EXISTS SRM_XCH_STREAM (
 CONNECTOR_ID varchar(20) NOT NULL, RESOURCE varchar(32) NOT NULL, BUSINESS_KEY varchar(96) NOT NULL,
 VERSION bigint NOT NULL DEFAULT 0, PRIMARY KEY(CONNECTOR_ID,RESOURCE,BUSINESS_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_XCH_INBOX (
 ID varchar(20) PRIMARY KEY, CONNECTOR_ID varchar(20) NOT NULL, EVENT_KEY varchar(96) NOT NULL,
 RESOURCE varchar(32) NOT NULL, BUSINESS_KEY varchar(96) NOT NULL, SOURCE_VERSION bigint NOT NULL,
 REQUEST_HASH char(64) NOT NULL, DATA_HASH char(64) NOT NULL, PAYLOAD_CIPHER longtext NOT NULL,
 STATUS varchar(32) NOT NULL, ATTEMPTS int NOT NULL DEFAULT 0, LAST_ERROR varchar(160) NULL,
 NEXT_RETRY_AT datetime(3) NOT NULL, CREATED_AT datetime(3) NOT NULL, APPLIED_AT datetime(3) NULL,
 UNIQUE KEY uq_xch_inbox(CONNECTOR_ID,EVENT_KEY), INDEX idx_xch_inbox_work(STATUS,NEXT_RETRY_AT),
 INDEX idx_xch_inbox_stream(CONNECTOR_ID,RESOURCE,BUSINESS_KEY,SOURCE_VERSION),
 FOREIGN KEY(CONNECTOR_ID) REFERENCES SRM_XCH_CONNECTOR(ID)
);
CREATE TABLE IF NOT EXISTS SRM_XCH_JOURNAL (
 CONNECTOR_ID varchar(20) NOT NULL, RESOURCE varchar(32) NOT NULL, BUSINESS_KEY varchar(96) NOT NULL,
 VERSION bigint NOT NULL, DATA_HASH char(64) NOT NULL, INBOX_ID varchar(20) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, PRIMARY KEY(CONNECTOR_ID,RESOURCE,BUSINESS_KEY,VERSION)
);
CREATE TABLE IF NOT EXISTS SRM_XCH_OUTBOX (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SYSTEM_KEY varchar(16) NOT NULL,
 MODE varchar(12) NOT NULL, CONNECTOR_ID varchar(20) NOT NULL, BUSINESS_TYPE varchar(40) NOT NULL,
 BUSINESS_ID varchar(64) NOT NULL, BUSINESS_VERSION bigint NOT NULL, EVENT_KEY varchar(96) NOT NULL,
 PAYLOAD_CIPHER longtext NOT NULL, REQUEST_HASH char(64) NOT NULL, STATUS varchar(24) NOT NULL,
 ATTEMPTS int NOT NULL DEFAULT 0, NEXT_RETRY_AT datetime(3) NOT NULL, LEASE_ID varchar(40) NULL,
 LEASE_UNTIL datetime(3) NULL, LAST_ERROR varchar(160) NULL, REMOTE_REF varchar(128) NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL, DELIVERED_AT datetime(3) NULL,
 UNIQUE KEY uq_xch_business(ORG_ID,BUSINESS_TYPE,BUSINESS_ID,BUSINESS_VERSION),
 UNIQUE KEY uq_xch_event(EVENT_KEY), INDEX idx_xch_outbox_work(STATUS,NEXT_RETRY_AT,LEASE_UNTIL),
 FOREIGN KEY(CONNECTOR_ID) REFERENCES SRM_XCH_CONNECTOR(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_SUPPLIER_MAP (
 CONNECTOR_ID varchar(20) NOT NULL, EXTERNAL_KEY varchar(80) NOT NULL, ORG_ID varchar(20) NOT NULL,
 SUPPLIER_ID varchar(20) NOT NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 PRIMARY KEY(CONNECTOR_ID,EXTERNAL_KEY), FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_EXTERNAL_MASTER (
 CONNECTOR_ID varchar(20) NOT NULL, EXTERNAL_KEY varchar(80) NOT NULL, ORG_ID varchar(20) NOT NULL,
 SOURCE_VERSION bigint NOT NULL, PAYLOAD_CIPHER mediumtext NOT NULL, UPDATED_AT datetime(3) NOT NULL,
 PRIMARY KEY(CONNECTOR_ID,EXTERNAL_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_COL_PO (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 CONNECTOR_ID varchar(20) NOT NULL, MODE varchar(12) NOT NULL, EXTERNAL_KEY varchar(96) NOT NULL,
 PO_NO varchar(64) NOT NULL, CURRENCY char(3) NOT NULL, SOURCE_VERSION bigint NOT NULL,
 ROW_VERSION bigint NOT NULL DEFAULT 0, CONFIRMED_VERSION bigint NOT NULL DEFAULT 0,
 STATUS varchar(24) NOT NULL, CANCELLED boolean NOT NULL DEFAULT false, CREATED_BY varchar(20) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, UPDATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_col_po(CONNECTOR_ID,EXTERNAL_KEY), UNIQUE KEY uq_col_pono(ORG_ID,PO_NO),
 INDEX idx_col_po_scope(ORG_ID,SUPPLIER_ID,CREATED_BY,STATUS), FOREIGN KEY(SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_PO_LINE (
 ID varchar(20) PRIMARY KEY, PO_ID varchar(20) NOT NULL, LINE_KEY varchar(40) NOT NULL,
 MATERIAL varchar(128) NOT NULL, QUANTITY decimal(18,3) NOT NULL, UNIT_PRICE_CIPHER text NOT NULL,
 DUE_DATE date NOT NULL, ACTIVE boolean NOT NULL DEFAULT true,
 UNIQUE KEY uq_col_po_line(PO_ID,LINE_KEY), INDEX idx_col_due(DUE_DATE,ACTIVE),
 FOREIGN KEY(PO_ID) REFERENCES SRM_COL_PO(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_PO_HISTORY (
 ID varchar(20) PRIMARY KEY, PO_ID varchar(20) NOT NULL, SOURCE_VERSION bigint NOT NULL,
 PAYLOAD_CIPHER mediumtext NOT NULL, CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_col_po_hist(PO_ID,SOURCE_VERSION)
);
CREATE TABLE IF NOT EXISTS SRM_COL_PO_CHANGE (
 ID varchar(20) PRIMARY KEY, PO_ID varchar(20) NOT NULL, BASE_VERSION bigint NOT NULL,
 STATUS varchar(24) NOT NULL, PREVIOUS_STATUS varchar(24) NOT NULL, PROPOSAL_CIPHER mediumtext NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL, CREATED_BY varchar(20) NOT NULL,
 CREATED_AT datetime(3) NOT NULL, CLOSED_AT datetime(3) NULL, UNIQUE KEY uq_col_change_request(PO_ID,REQUEST_KEY)
);
CREATE TABLE IF NOT EXISTS SRM_COL_POLICY_HEAD (
 ORG_ID varchar(20) PRIMARY KEY, VERSION bigint NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS SRM_COL_POLICY (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, VERSION bigint NOT NULL,
 TOLERANCE_PCT decimal(7,3) NOT NULL, REASON varchar(500) NOT NULL,
 CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL, UNIQUE KEY uq_col_policy(ORG_ID,VERSION)
);
CREATE TABLE IF NOT EXISTS SRM_COL_ASN (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 PO_ID varchar(20) NOT NULL, ASN_NO varchar(64) NOT NULL, ETA_MS bigint NULL,
 CARRIER varchar(80) NULL, TRACKING_NO varchar(96) NULL, STATUS varchar(24) NOT NULL,
 ROW_VERSION bigint NOT NULL DEFAULT 0, TOLERANCE_PCT decimal(7,3) NOT NULL, POLICY_VERSION bigint NOT NULL,
 DIFF_FLAG varchar(20) NOT NULL DEFAULT 'NORMAL', CREATED_BY varchar(20) NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 UNIQUE KEY uq_col_asn_no(ORG_ID,ASN_NO), UNIQUE KEY uq_col_asn_req(PO_ID,REQUEST_KEY),
 FOREIGN KEY(PO_ID) REFERENCES SRM_COL_PO(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_ASN_LINE (
 ID varchar(20) PRIMARY KEY, ASN_ID varchar(20) NOT NULL, PO_LINE_ID varchar(20) NOT NULL,
 BATCH_NO varchar(80) NOT NULL, QUANTITY decimal(18,3) NOT NULL,
 FOREIGN KEY(ASN_ID) REFERENCES SRM_COL_ASN(ID), FOREIGN KEY(PO_LINE_ID) REFERENCES SRM_COL_PO_LINE(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_RECEIPT (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 PO_ID varchar(20) NOT NULL, ASN_ID varchar(20) NOT NULL, RECEIPT_NO varchar(64) NOT NULL,
 CONNECTOR_ID varchar(20) NULL, EXTERNAL_KEY varchar(96) NULL, SOURCE_VERSION bigint NOT NULL DEFAULT 0,
 FINAL_RECEIPT boolean NOT NULL, STATUS varchar(20) NOT NULL, ACTIVE_MARK varchar(8) NULL DEFAULT 'CURRENT', ROW_VERSION bigint NOT NULL DEFAULT 0,
 RECEIVED_MS bigint NOT NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL,
 UNIQUE KEY uq_col_receipt_no(ORG_ID,RECEIPT_NO,ACTIVE_MARK), UNIQUE KEY uq_col_receipt_req(ORG_ID,REQUEST_KEY),
 UNIQUE KEY uq_col_receipt_source(CONNECTOR_ID,EXTERNAL_KEY,SOURCE_VERSION), FOREIGN KEY(ASN_ID) REFERENCES SRM_COL_ASN(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_RECEIPT_LINE (
 ID varchar(20) PRIMARY KEY, RECEIPT_ID varchar(20) NOT NULL, ASN_LINE_ID varchar(20) NOT NULL,
 PO_LINE_ID varchar(20) NOT NULL, QUANTITY decimal(18,3) NOT NULL, UNIT_PRICE_CIPHER text NOT NULL,
 AMOUNT_CIPHER text NOT NULL, PO_VERSION bigint NOT NULL, ALLOC_RECON_ID varchar(20) NULL,
 UNIQUE KEY uq_col_received_line(RECEIPT_ID,ASN_LINE_ID), FOREIGN KEY(RECEIPT_ID) REFERENCES SRM_COL_RECEIPT(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_MES (
 CONNECTOR_ID varchar(20) NOT NULL, PO_ID varchar(20) NOT NULL, SOURCE_VERSION bigint NOT NULL,
 PRIORITY int NOT NULL, SOURCE_REF varchar(128) NOT NULL, PAYLOAD_CIPHER mediumtext NOT NULL,
 UPDATED_AT datetime(3) NOT NULL, PRIMARY KEY(CONNECTOR_ID,PO_ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_RECON (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 REC_NO varchar(64) NOT NULL, CURRENCY char(3) NOT NULL, MODE varchar(12) NOT NULL,
 STATUS varchar(24) NOT NULL, ROW_VERSION bigint NOT NULL DEFAULT 0,
 QUANTITY decimal(20,3) NOT NULL, AMOUNT_CIPHER text NOT NULL, BASIS_HASH char(64) NOT NULL,
 BUYER_CONFIRMED boolean NOT NULL DEFAULT false, SUPPLIER_CONFIRMED boolean NOT NULL DEFAULT false,
 INVOICE_ID varchar(20) NULL, CREATED_BY varchar(20) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 REQUEST_KEY varchar(64) NOT NULL, REQUEST_HASH char(64) NOT NULL,
 UNIQUE KEY uq_col_recno(ORG_ID,REC_NO), UNIQUE KEY uq_col_recreq(ORG_ID,REQUEST_KEY),
 INDEX idx_col_rec_scope(ORG_ID,SUPPLIER_ID,CREATED_BY,STATUS)
);
CREATE TABLE IF NOT EXISTS SRM_COL_RECON_LINE (
 ID varchar(20) PRIMARY KEY, RECON_ID varchar(20) NOT NULL, RECEIPT_LINE_ID varchar(20) NOT NULL,
 PO_ID varchar(20) NOT NULL, PO_LINE_ID varchar(20) NOT NULL, QUANTITY decimal(18,3) NOT NULL,
 UNIT_PRICE_CIPHER text NOT NULL, AMOUNT_CIPHER text NOT NULL,
 UNIQUE KEY uq_col_rec_line(RECON_ID,RECEIPT_LINE_ID), FOREIGN KEY(RECON_ID) REFERENCES SRM_COL_RECON(ID)
);
CREATE TABLE IF NOT EXISTS SRM_COL_RECON_ACTION (
