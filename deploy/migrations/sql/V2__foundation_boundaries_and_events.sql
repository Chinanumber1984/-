CREATE TABLE SRM_ATTACHMENT_SCOPE (
 ID varchar(20) PRIMARY KEY, FILE_ID varchar(64) NOT NULL UNIQUE,
 ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 OWNER_USER_ID varchar(20) NOT NULL, CONTENT_SHA256 char(64) NOT NULL,
 VISIBILITY varchar(16) NOT NULL DEFAULT 'PRIVATE', CREATED_AT datetime(3) NOT NULL,
 INDEX idx_attachment_scope (ORG_ID,SUPPLIER_ID),
 CONSTRAINT fk_attachment_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE SRM_APPROVAL_LINK (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 BUSINESS_TYPE varchar(32) NOT NULL, BUSINESS_ID varchar(20) NOT NULL,
 PROCESS_INSTANCE_ID varchar(64) NOT NULL UNIQUE, STATUS varchar(16) NOT NULL,
 ROW_VERSION bigint NOT NULL DEFAULT 0, CREATED_AT datetime(3) NOT NULL,
 INDEX idx_approval_scope (ORG_ID,SUPPLIER_ID),
 CONSTRAINT fk_approval_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
CREATE TABLE SRM_EVENT_OUTBOX (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL,
 EVENT_KEY varchar(128) NOT NULL UNIQUE, BUSINESS_KEY varchar(128) NOT NULL,
 EVENT_TYPE varchar(64) NOT NULL, PAYLOAD json NOT NULL,
 STATUS varchar(16) NOT NULL DEFAULT 'PENDING', ATTEMPTS int NOT NULL DEFAULT 0,
 NEXT_RETRY_AT datetime(3) NOT NULL, CREATED_AT datetime(3) NOT NULL,
 INDEX idx_outbox_retry (STATUS,NEXT_RETRY_AT), INDEX idx_outbox_scope (ORG_ID,BUSINESS_KEY)
);
CREATE TABLE SRM_BUSINESS_EVENT (
 ID varchar(20) PRIMARY KEY, ORG_ID varchar(20) NOT NULL, SUPPLIER_ID varchar(20) NOT NULL,
 SUBJECT_ID varchar(64) NOT NULL, ACTOR_ID varchar(20) NOT NULL, ACTION varchar(64) NOT NULL,
 TRACE_ID varchar(64) NOT NULL, METADATA json NOT NULL, CREATED_AT datetime(3) NOT NULL,
 INDEX idx_event_scope (ORG_ID,SUPPLIER_ID,CREATED_AT),
 CONSTRAINT fk_event_supplier FOREIGN KEY (SUPPLIER_ID) REFERENCES SRM_SUPPLIER(ID)
);
-- PAYLOAD and METADATA hold references and non-sensitive event data. Raw secrets/prices/accounts are forbidden.
-- Signatures/retention and outbox dispatch workers are later business/operations deliverables.
